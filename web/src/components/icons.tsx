export type IconName = keyof typeof paths

export function Icon({ name, size = 16, className = '', style, title, fill, stroke = 1.9 }: P & { name: IconName }) {
  return (
    <svg className={`icon ${className}`} style={style} width={size} height={size} viewBox="0 0 24 24" fill={fill ? 'currentColor' : 'none'} stroke="currentColor" strokeWidth={stroke} strokeLinecap="round" strokeLinejoin="round" aria-hidden={title ? undefined : true} role={title ? 'img' : undefined}>
      {title && <title>{title}</title>}
      {paths[name]}
    </svg>
  )
}

/** The kind of a file, from its type and name: icon and colour. */
export function fileKind(name: string, mime: string, isDir: boolean): { icon: IconName; color: string; label: string } {
  if (isDir) return { icon: 'folder', color: '#e0a526', label: 'Folder' }
  const ext = name.includes('.') ? name.split('.').pop()!.toLowerCase() : ''
  if (mime.startsWith('image/')) return { icon: 'image', color: '#16a34a', label: 'Image' }
  if (mime.startsWith('video/')) return { icon: 'film', color: '#db2777', label: 'Video' }
  if (mime.startsWith('audio/')) return { icon: 'music', color: '#9333ea', label: 'Audio' }
  if (mime === 'application/pdf') return { icon: 'pdf', color: '#dc2626', label: 'PDF' }
  if (/^(doc|docx|odt|rtf|pages)$/.test(ext)) return { icon: 'fileText', color: '#2563eb', label: 'Document' }
  if (/^(xls|xlsx|ods|csv|numbers)$/.test(ext)) return { icon: 'sheet', color: '#059669', label: 'Spreadsheet' }
  if (/^(ppt|pptx|odp|key)$/.test(ext)) return { icon: 'slides', color: '#ea580c', label: 'Presentation' }
  if (/^(zip|7z|rar|gz|tgz|tar|bz2|xz|zst|iso|dmg)$/.test(ext)) return { icon: 'archive', color: '#a16207', label: 'Archive' }
  if (/^(epub|mobi|azw3|cbz|cbr)$/.test(ext)) return { icon: 'book', color: '#7c3aed', label: 'Book' }
  if (/^(go|py|js|ts|tsx|jsx|rs|c|h|cpp|java|sh|rb|php|sql|nix|json|yaml|yml|toml|html|css|xml|lua|kt|swift)$/.test(ext)) return { icon: 'fileCode', color: '#0891b2', label: 'Code' }
  if (mime.startsWith('text/') || /^(md|txt|log|srt|vtt|ass|nfo|ini|conf|cue)$/.test(ext)) return { icon: 'fileText', color: '#64748b', label: 'Text' }
  return { icon: 'file', color: '#94a3b8', label: ext ? ext.toUpperCase() + ' file' : 'File' }
}

